import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const edge = readFileSync(new URL('../supabase/functions/delete-managed-user/index.ts', import.meta.url), 'utf8')
const users = readFileSync(new URL('../studio/src/UsersManager.jsx', import.meta.url), 'utf8')
const panels = readFileSync(new URL('../studio/src/users/UserPanels.jsx', import.meta.url), 'utf8')
const styles = readFileSync(new URL('../studio/src/styles/users.css', import.meta.url), 'utf8')

assert.match(edge, /\["admin","super_admin"\]\.includes\(callerRole\)/, 'Only Admin or Super Admin are allowed.')
assert.match(edge, /trustedCallerRole !== callerRole/, 'Both server-trusted role claims must match.')
assert.match(edge, /validateLiveAdminSession\(admin, caller\.id, token\)/, 'Live MFA is mandatory.')
assert.match(edge, /targetId === caller\.id/, 'Deleting yourself is prohibited.')
assert.match(edge, /rank\[callerRole\] <= rank\[targetRole\]/, 'No same-rank or higher-rank deletions.')
assert.match(edge, /consumeRateLimit\(admin, "manage_user_access"/, 'Destructive actions remain rate limited.')
assert.match(edge, /action === "preview_delete" \|\| action === "delete"/, 'Preview and destructive operations have separate actions.')
assert.match(edge, /if \(action === "preview_delete"\)/, 'Preview never deletes.')
assert.match(edge, /const blockers = await protectedHistory\(admin, targetId\)/, 'History must be freshly checked for every request.')
assert.match(edge, /if \(blockers\.length > 0\)/, 'Deletion must fail closed if records appear.')
assert.match(edge, /if \(error \|\| count === null\) throw/, 'Unverified database references deny deletion.')
assert.match(edge, /confirmationEmail !== targetEmail \|\| body\.confirmation_text !== "ELIMINAR"/, 'Server requires two confirmations.')
assert.match(edge, /auditRequestError\) return reply/, 'A failed pre-deletion audit must stop the operation.')
assert.ok(edge.indexOf('await admin.auth.admin.deleteUser(targetId)') > edge.indexOf('const blockers = await protectedHistory'), 'Auth deletion happens only after history checks.')
assert.match(edge, /delete_managed_user_requested/, 'Record deletion intent before deletion.')
assert.match(edge, /delete_managed_user"/, 'Record successful deletion.')
for (const label of ['enrollments', 'block_progress', 'exam_attempts', 'certificates', 'legal_acceptances', 'compliance_evidence', 'privacy_requests', 'audit_logs', 'courses', 'profile_position_history']) {
  assert.ok(edge.includes('["' + label + '"'), 'Deletion must protect ' + label + '.')
}
assert.match(edge, /action === "delete"/, 'Permanent delete is explicit.')
assert.match(edge, /action = body\.action === undefined \? "toggle_access"/, 'Legacy deactivate/reactivate calls remain backwards compatible.')
assert.match(users, /canManage\(person\) && <button[^\n]*user-delete-icon/, 'Desktop list permits authorized deletion.')
assert.match(users, /className="danger-button compact user-delete-action"/, 'Mobile list permits authorized deletion.')
assert.match(users, /action: 'preview_delete'/, 'UI previews history before confirmation.')
assert.match(users, /action: 'delete'/, 'UI requests deletion through the Edge Function.')
assert.match(users, /data\.deleted !== true/, 'UI never reports success without server confirmation.')
assert.match(panels, /export function DeleteUserModal/, 'Confirmation modal exists.')
assert.match(panels, /confirmationText === 'ELIMINAR'/, 'Modal requires typed confirmation.')
assert.match(panels, /!confirmed \|\| busy/, 'Delete button remains disabled without confirmation.')
assert.match(panels, /onDelete/, 'User drawer exposes the same action.')
assert.match(styles, /user-delete-modal/, 'Responsive dialog has its own styles.')
assert.doesNotMatch(users, /auth\.admin\.deleteUser/, 'Admin credentials are never exposed in browser.')
console.log('Protected permanent account deletion authorization and UI contracts: OK')
